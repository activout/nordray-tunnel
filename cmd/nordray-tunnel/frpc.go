// frpcConfig mirrors the upstream frpc TOML schema; field names are upstream's.
type frpcConfig struct {
	ServerAddr    string `toml:"serverAddr"`
	ServerPort    int    `toml:"serverPort"`
	LoginFailExit bool   `toml:"loginFailExit"`
	Auth          struct {
		Method string `toml:"method"`
		Token  string `toml:"token"`
	} `toml:"auth"`
	Transport struct {
		Protocol string `toml:"protocol"`
		TLS      struct {
			Enable        bool   `toml:"enable"`
			TrustedCaFile string `toml:"trustedCaFile"`
			ServerName    string `toml:"serverName"`
		} `toml:"tls"`
	} `toml:"transport"`
	WebServer *struct {
		Addr     string `toml:"addr"`
		Port     int    `toml:"port"`
		User     string `toml:"user"`
		Password string `toml:"password"`
	} `toml:"webServer,omitempty"`
	Log struct {
		To    string `toml:"to"`
		Level string `toml:"level"`
	} `toml:"log"`
	Proxies []frpcProxy `toml:"proxies"`
}

type frpcProxy struct {
	Name           string   `toml:"name"`
	Type           string   `toml:"type"`
	LocalIP        string   `toml:"localIP"`
	LocalPort      int      `toml:"localPort"`
	CustomDomains  []string `toml:"customDomains"`
	RequestHeaders struct {
		Set map[string]string `toml:"set"`
	} `toml:"requestHeaders"`
}

// caFileName is written next to frpc.toml and referenced relatively; run
// starts frpc in that directory, so an exported config works anywhere.
const caFileName = "ca.pem"

// buildFrpcConfig renders the agent configuration. frpc must always be given
// a trusted CA file: without one it skips server certificate verification
// for wss and TLS alike (frp v0.71.1, pkg/transport/tls.go).
func buildFrpcConfig(s *State, token string, admin *adminServer) (*frpcConfig, error) {
	c := &frpcConfig{LoginFailExit: false}
	c.Auth.Method, c.Auth.Token = "token", token
	c.Transport.TLS.TrustedCaFile = caFileName
	switch s.Transport {
	case "wss":
		if s.TunnelHost == "" {
			return nil, fmt.Errorf("installation %q has no tunnel endpoint yet; run setup", s.Name)
		}
		c.ServerAddr, c.ServerPort = s.TunnelHost, 443
		c.Transport.Protocol = "wss"
	case "anycast":
		host, port, err := net.SplitHostPort(s.AnycastAddr)
		if err != nil {
			return nil, fmt.Errorf("installation %q has no Anycast address yet; run setup", s.Name)
		}
		c.ServerAddr = host
		c.ServerPort, _ = strconv.Atoi(port)
		c.Transport.Protocol = "tcp"
		c.Transport.TLS.Enable = true
		c.Transport.TLS.ServerName = relayServerName
	default:
		return nil, fmt.Errorf("unknown transport %q", s.Transport)
	}
	if admin != nil {
		c.WebServer = &struct {
			Addr     string `toml:"addr"`
			Port     int    `toml:"port"`
			User     string `toml:"user"`
			Password string `toml:"password"`
		}{"127.0.0.1", admin.Port, admin.User, admin.Password}
	}
	c.Log.To, c.Log.Level = "console", "info"
	for _, p := range s.Proxies {
		px := frpcProxy{Name: p.Name, Type: "http", LocalIP: p.LocalIP, LocalPort: p.LocalPort, CustomDomains: []string{p.Hostname}}
		// frps sets X-Forwarded-Proto: http because Bunny reaches it over
		// HTTP. Visitors always use HTTPS (add forces it on the hostname),
		// so tell the service the truth. frps applies this after its own
		// X-Forwarded-* handling (pkg/util/vhost/http.go).
		px.RequestHeaders.Set = map[string]string{"X-Forwarded-Proto": "https"}
		c.Proxies = append(c.Proxies, px)
	}
	return c, nil
}

// caBundle returns the PEM the agent trusts: the installation CA for
// anycast, otherwise the NSS (Mozilla) roots shipped with this binary.
// Roots with constraints that PEM cannot express are left out.
func caBundle(s *State) []byte {
	if s.Transport == "anycast" {
		return []byte(s.CACert)
	}
	var b bytes.Buffer
	for r := range bundle.Roots() {
		if r.Constraint == nil {
			_ = pem.Encode(&b, &pem.Block{Type: "CERTIFICATE", Bytes: r.Certificate})
		}
	}
	return b.Bytes()
}

// writeAgentFiles writes frpc.toml and ca.pem into dir with private
// permissions. frpc.toml contains the tunnel token in plain text, because
// upstream frpc reads it from the file.
func writeAgentFiles(dir string, s *State, cfg *frpcConfig) (string, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	var b bytes.Buffer
	b.WriteString("# Generated by nordray-tunnel. Contains the tunnel token: keep private.\n")
	if err := toml.NewEncoder(&b).Encode(cfg); err != nil {
		return "", err
	}
	path := filepath.Join(dir, "frpc.toml")
	if err := writePrivate(path, b.Bytes()); err != nil {
		return "", err
	}
	return path, writePrivate(filepath.Join(dir, caFileName), caBundle(s))
}

func writePrivate(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o600); err != nil { // WriteFile keeps an existing file's mode
		return err
	}
	return os.Rename(tmp, path)
}
